// Messages (SPEC §6). Encoding keeps Python's key order, so the bytes match exactly.

export const encode = (msg) => utf8(JSON.stringify(msg));

export const scan = () => ({ type: "scan" });

export function setCredentials(ssid, security, psk) {
  return { type: "set_credentials", ssid, hidden: false, security, psk };
}

function load(bytes) {
  let obj;
  try {
    obj = JSON.parse(decoder.decode(bytes));
  } catch {
    throw new ProtocolError("message is not valid UTF-8 JSON");
  }
  if (obj === null || typeof obj !== "object" || Array.isArray(obj)) {
    throw new ProtocolError("message is not an object");
  }
  return obj;
}

function fields(d, required, optional = []) {
  for (const key of required) if (!(key in d)) throw new ProtocolError(`missing field: ${key}`);
  for (const key of Object.keys(d)) {
    if (!required.includes(key) && !optional.includes(key)) {
      throw new ProtocolError("unexpected field");
    }
  }
}

const isInt = (v) => Number.isInteger(v);

function str(v, name) {
  if (typeof v !== "string") throw new ProtocolError(`${name} must be a string`);
  return v;
}

function oneOf(v, values, name) {
  if (!values.includes(v)) throw new ProtocolError(`${name} has an unknown value`);
  return v;
}

function bytesOf(v, length, name) {
  const b = unb64(v, name);
  if (b.length !== length) throw new ProtocolError(`${name} must be ${length} bytes`);
  return b;
}

function deviceId(v) {
  const re = new RegExp(`^${C.DEVICE_ID_PREFIX}[0-9A-F]{6}$`);
  if (typeof v !== "string" || !re.test(v)) throw new ProtocolError("device_id is not valid");
  return v;
}

function version(v) {
  if (v !== C.PROTOCOL_VERSION) throw new ProtocolError("unsupported protocol version");
}

function error(d) {
  fields(d, ["code"], ["retry_after_s"]);
  const code = oneOf(d.code, C.ERROR_CODES, "code");
  const rateLimited = code === "rate_limited";
  if (rateLimited !== ("retry_after_s" in d)) {
    throw new ProtocolError("retry_after_s goes with rate_limited only");
  }
  if (rateLimited && !(isInt(d.retry_after_s) && d.retry_after_s >= 1)) {
    throw new ProtocolError("retry_after_s must be a positive integer");
  }
  return { type: "error", code, retryAfterS: rateLimited ? d.retry_after_s : null };
}

/** What the device sends on `session`: hello_reply, handshake_failed or error. */
export function decodeSession(bytes) {
  const d = load(bytes);
  const type = d.type;
  delete d.type;
  if (type === "hello_reply") {
    fields(d, ["v", "device_id", "pub", "nonce", "confirm"]);
    version(d.v);
    return {
      type,
      deviceId: deviceId(d.device_id),
      pub: bytesOf(d.pub, C.PUBLIC_KEY_BYTES, "pub"),
      nonce: bytesOf(d.nonce, C.HANDSHAKE_NONCE_BYTES, "nonce"),
      confirm: bytesOf(d.confirm, C.CONFIRM_BYTES, "confirm"),
    };
  }
  if (type === "handshake_failed") {
    fields(d, []);
    return { type };
  }
  if (type === "error") return error(d);
  throw new ProtocolError("message type is not allowed on session");
}

export function decodeEnvelope(bytes) {
  const d = load(bytes);
  fields(d, ["seq", "ct"]);
  if (!isInt(d.seq) || d.seq < 0 || d.seq > C.MAX_SEQ) throw new ProtocolError("bad seq");
  return { seq: d.seq, ct: unb64(d.ct, "ct") };
}

function network(n) {
  if (n === null || typeof n !== "object" || Array.isArray(n)) {
    throw new ProtocolError("network must be an object");
  }
  fields(n, ["ssid", "signal", "security"]);
  const ssid = str(n.ssid, "ssid");
  const size = utf8(ssid).length;
  if (size < 1 || size > C.MAX_SSID_BYTES) throw new ProtocolError("ssid has a bad length");
  if (!isInt(n.signal) || n.signal < 0 || n.signal > 100) throw new ProtocolError("bad signal");
  return { ssid, signal: n.signal, security: oneOf(n.security, C.SECURITY, "security") };
}

function status(d) {
  fields(d, ["state"], ["ip", "internet", "warnings", "reason"]);
  const state = oneOf(d.state, C.STATUS_STATES, "state");
  const connected = state === "connected";
  const failed = state === "failed";
  if (connected !== ("ip" in d) || connected !== ("internet" in d)) {
    throw new ProtocolError("ip and internet go with connected only");
  }
  if (failed !== ("reason" in d)) throw new ProtocolError("reason goes with failed only");
  const warnings = d.warnings ?? [];
  if (!Array.isArray(warnings) || (warnings.length && !connected)) {
    throw new ProtocolError("warnings go with connected only");
  }
  return {
    type: "status",
    state,
    ip: connected ? str(d.ip, "ip") : null,
    internet: connected ? oneOf(d.internet, C.INTERNET, "internet") : null,
    warnings: warnings.map((w) => oneOf(w, C.WARNINGS, "warnings")),
    reason: failed ? oneOf(d.reason, C.FAILURE_REASONS, "reason") : null,
  };
}

/** What the device sends inside a `status` envelope: ready, scan_result, status or error. */
export function decodeStatus(bytes) {
  const d = load(bytes);
  const type = d.type;
  delete d.type;
  if (type === "ready") {
    fields(d, []);
    return { type };
  }
  if (type === "scan_result") {
    fields(d, ["networks"]);
    if (!Array.isArray(d.networks) || d.networks.length > C.MAX_SCAN_NETWORKS) {
      throw new ProtocolError("networks must be a list");
    }
    return { type, networks: d.networks.map(network) };
  }
  if (type === "status") return status(d);
  if (type === "error") return error(d);
  throw new ProtocolError("message type is not allowed on status");
}

export function decodeInfo(bytes) {
  const d = load(bytes);
  fields(d, ["v", "device_id", "name", "state", "caps"]);
  version(d.v);
  if (!Array.isArray(d.caps)) throw new ProtocolError("caps must be a list");
  return {
    deviceId: deviceId(d.device_id),
    name: str(d.name, "name"),
    state: oneOf(d.state, C.DEVICE_STATES, "state"),
    caps: d.caps.map((c) => oneOf(c, C.SECURITY, "caps")),
  };
}

// ---------------------------------------------------------------------------
// The client: whole messages over a chunk link, and the protocol steps (client.py).
//
// The link is three functions the page (Web Bluetooth) or a test (a socket) provides:
//   send(channel, chunk)   writes one chunk, with response; rejects when the link is gone
// and the link calls back:
//   client.onChunk(channel, chunk)   for every notification on session and status
//   client.lost()                    when the link drops (gattserverdisconnected, Q110)

export class Client {
  constructor(send, reassemblerClock) {
    this._send = send;
    this._reassemblers = {
      session: new Reassembler(reassemblerClock),
      status: new Reassembler(reassemblerClock),
    };
    this._inbox = []; // [channel, bytes], in arrival order: some steps wait for either
    this._waiter = null;
    this._lost = false;
    this.cipher = null;
  }

  // --- the link -------------------------------------------------------------------------

  onChunk(channel, chunk) {
    let message;
    try {
      message = this._reassemblers[channel].feed(chunk);
    } catch {
      return; // the reassembler has reset; the next message can still arrive
    }
    if (message === null) return;
    this._inbox.push([channel, message]);
    this._wake();
  }

  lost() {
    this._lost = true;
    this._wake();
  }

  _wake() {
    const waiter = this._waiter;
    this._waiter = null;
    if (waiter) waiter();
  }

  async _sendMessage(channel, bytes) {
    if (this._lost) throw new ConnectionLostError("the connection is gone");
    try {
      for (const chunk of frame(bytes)) await this._send(channel, chunk);
    } catch (e) {
      if (e instanceof FramingError) throw e;
      throw new ConnectionLostError("a write failed");
    }
  }

  /** The next message from the device, decoded (and decrypted, on status). */
  async receive(timeoutS) {
    const deadline = Date.now() + timeoutS * 1000;
    while (!this._inbox.length) {
      if (this._lost) throw new ConnectionLostError("the connection is gone");
      const left = deadline - Date.now();
      if (left <= 0) throw new NoReplyError(`no reply within ${timeoutS} s`);
      await new Promise((resolve) => {
        const timer = setTimeout(resolve, left);
        this._waiter = () => {
          clearTimeout(timer);
          resolve();
        };
      });
    }
    const [channel, bytes] = this._inbox.shift();
    if (channel === "session") return [channel, decodeSession(bytes)];
    if (!this.cipher) throw new ProtocolError("encrypted message before the handshake");
    return [channel, decodeStatus(await this.cipher.open(decodeEnvelope(bytes)))];
  }

  // --- the steps ------------------------------------------------------------------------

  /**
   * SPEC §5.1. May be called again after WrongCodeError or RateLimitedError: a new hello on
   * the same connection (review Q4). `info` is the decoded info read before.
   */
  async handshake(code, info, random = randomBytes) {
    const handshake = await Handshake.start(code, random);
    this._newSession();
    await this._sendMessage("session", encode(handshake.hello()));
    const [, reply] = await this.receive(C.REPLY_WAIT_S); // no reply: window closed (Q22)
    if (reply.type === "error" && reply.code === "rate_limited") {
      throw new RateLimitedError(reply.retryAfterS);
    }
    if (reply.type !== "hello_reply") throw new ProtocolError(`expected hello_reply`);
    if (reply.deviceId !== info.deviceId) {
      throw new ProtocolError("hello_reply comes from a different device than info"); // Q34
    }
    const { confirm, keys } = await handshake.onHelloReply(reply);
    this.cipher = await Cipher.create(keys);
    await this._sendMessage("session", encode(confirm));
    const [, answer] = await this.receive(C.REPLY_WAIT_S);
    if (answer.type === "handshake_failed") throw new WrongCodeError("the device rejected us");
    if (answer.type !== "ready") throw new ProtocolError("expected ready");
  }

  async scan() {
    await this._sendCommand(scan());
    const msg = await this._receiveStatus(C.SCAN_WAIT_S);
    if (msg.type !== "scan_result") throw new ProtocolError("expected scan_result");
    return msg.networks;
  }

  /** Yields `connecting`, then `connected` or `failed` (after `failed`, retry is possible). */
  async *provision(creds) {
    await this._sendCommand(creds);
    const first = await this._receiveStatus(C.REPLY_WAIT_S);
    if (first.type !== "status" || first.state !== "connecting") {
      throw new ProtocolError("expected connecting");
    }
    yield first;
    const result = await this._receiveStatus(C.RESULT_WAIT_S);
    if (result.type !== "status" || result.state === "connecting") {
      throw new ProtocolError("expected connected or failed");
    }
    yield result;
  }

  _newSession() {
    this.cipher = null;
    for (const r of Object.values(this._reassemblers)) r.reset();
    this._inbox = [];
  }

  async _sendCommand(msg) {
    if (!this.cipher) throw new ProtocolError("no session established");
    await this._sendMessage("command", encode(await this.cipher.seal(encode(msg))));
  }

  async _receiveStatus(timeoutS) {
    const [channel, msg] = await this.receive(timeoutS);
    if (channel !== "status") throw new ProtocolError("expected a status message");
    if (msg.type === "error") throw new DeviceRefusedError(msg.code);
    return msg;
  }
}
