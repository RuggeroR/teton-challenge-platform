const encoder = new TextEncoder();
const decoder = new TextDecoder("utf-8", { fatal: true });
const subtle = () => globalThis.crypto.subtle;

// ---------------------------------------------------------------------------
// Typed errors, as in client.py (review Q33). The page picks a ui_text sentence for each.

export class ProtocolError extends Error {} // the device sent something we can't accept
export class WrongCodeError extends Error {} // the device's tag didn't match, or it rejected ours
export class NoReplyError extends Error {} // a wait ran out
export class ConnectionLostError extends Error {} // Bluetooth dropped, or a write failed
export class InvalidSetupCode extends Error {} // checked before anything is sent (Q28)
export class FramingError extends Error {}

export class RateLimitedError extends Error {
  constructor(retryAfterS) {
    super(`rate limited, retry after ${retryAfterS} s`);
    this.retryAfterS = retryAfterS;
  }
}

export class DeviceRefusedError extends Error {
  constructor(code) {
    super(`device refused: ${code}`);
    this.code = code;
  }
}

// ---------------------------------------------------------------------------
// Bytes

export const utf8 = (text) => encoder.encode(text);

function concat(...parts) {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let i = 0;
  for (const p of parts) {
    out.set(p, i);
    i += p.length;
  }
  return out;
}

export function b64(bytes) {
  let s = "";
  for (const b of bytes) s += String.fromCharCode(b);
  return btoa(s);
}

function unb64(text, name) {
  // Standard base64 only, as Python's b64decode(validate=True) accepts.
  if (typeof text !== "string" || text.length % 4 !== 0 || !/^[A-Za-z0-9+/]*={0,2}$/.test(text)) {
    throw new ProtocolError(`${name} is not valid base64`);
  }
  return Uint8Array.from(atob(text), (c) => c.charCodeAt(0));
}

// ---------------------------------------------------------------------------
// Setup code (SPEC §3): the normalised code is the HKDF salt, so it must match Python's.

const LOOK_ALIKES = { O: "0", I: "1", L: "1" };

export function normalizeCode(text) {
  const code = text
    .toUpperCase()
    .replace(/\s+/g, "")
    .replaceAll("-", "")
    .replace(/[OIL]/g, (c) => LOOK_ALIKES[c]);
  if ([...code].length !== C.CODE_LENGTH) throw new InvalidSetupCode("wrong length");
  for (const ch of code) {
    if (!C.CODE_ALPHABET.includes(ch)) throw new InvalidSetupCode("character not allowed");
  }
  return code;
}

// ---------------------------------------------------------------------------
// Framing (SPEC §4.1): [u16 big-endian length][payload], cut into 20-byte chunks.

export function frame(payload) {
  if (payload.length > C.MAX_MESSAGE_BYTES) throw new FramingError("message too large");
  const data = concat(Uint8Array.of(payload.length >> 8, payload.length & 0xff), payload);
  const chunks = [];
  for (let i = 0; i < data.length; i += C.CHUNK_SIZE_BYTES) {
    chunks.push(data.slice(i, i + C.CHUNK_SIZE_BYTES));
  }
  return chunks;
}

export class Reassembler {
  constructor(clock = () => Date.now() / 1000) {
    this._clock = clock;
    this._buffer = new Uint8Array(0);
    this._lastChunkAt = 0;
  }

  reset() {
    this._buffer = new Uint8Array(0);
  }

  /** Returns the payload when a message is complete, else null. Throws FramingError. */
  feed(chunk) {
    const now = this._clock();
    // 10 s without a new chunk drops a partial message (review Q94).
    if (this._buffer.length && now - this._lastChunkAt > C.REASSEMBLY_TIMEOUT_S) this.reset();
    if (!chunk.length) this._fail("empty chunk");
    this._lastChunkAt = now;
    this._buffer = concat(this._buffer, chunk);
    if (this._buffer.length < 2) return null;
    const length = (this._buffer[0] << 8) | this._buffer[1];
    if (length > C.MAX_MESSAGE_BYTES) this._fail("declared length too large");
    if (this._buffer.length < 2 + length) return null;
    if (this._buffer.length > 2 + length) this._fail("data after the end of the message");
    const payload = this._buffer.slice(2);
    this.reset();
    return payload;
  }

  _fail(reason) {
    this.reset();
    throw new FramingError(reason);
  }
}

