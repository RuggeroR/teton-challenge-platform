// Handshake, configurator side (SPEC §5.1, §5.2). One object per hello.

// A raw 32-byte X25519 private key, wrapped in the fixed PKCS8 header WebCrypto requires.
const PKCS8_X25519 = Uint8Array.of(
  0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x6e, 0x04, 0x22, 0x04, 0x20,
);

export const randomBytes = (n) => globalThis.crypto.getRandomValues(new Uint8Array(n));

async function x25519Key(raw) {
  // Any 32 random bytes are a valid X25519 private key, as in crypto.py's _new_key().
  const key = await subtle().importKey("pkcs8", concat(PKCS8_X25519, raw), { name: "X25519" },
    true, ["deriveBits"]);
  const jwk = await subtle().exportKey("jwk", key); // the only portable way to its public key
  const pub = Uint8Array.from(atob(jwk.x.replace(/-/g, "+").replace(/_/g, "/")), (c) =>
    c.charCodeAt(0));
  return { key, pub };
}

async function sha256(data) {
  return new Uint8Array(await subtle().digest("SHA-256", data));
}

export class Handshake {
  /** `code` must already be valid (normalizeCode); `random` is injectable for the vectors. */
  static async start(code, random = randomBytes) {
    const { key, pub } = await x25519Key(random(32));
    return new Handshake(normalizeCode(code), key, pub, random(C.HANDSHAKE_NONCE_BYTES));
  }

  constructor(code, key, pub, nonce) {
    this._code = code;
    this._key = key;
    this.pub = pub;
    this.nonce = nonce;
  }

  hello() {
    return { type: "hello", v: C.PROTOCOL_VERSION, pub: b64(this.pub), nonce: b64(this.nonce) };
  }

  /**
   * Checks the device's tag; only then returns our confirm message and the session keys.
   * Throws WrongCodeError when the tag doesn't match: nothing is sent then (SPEC §5.1).
   */
  async onHelloReply(reply) {
    if (!this._key) throw new ProtocolError("handshake already finished");
    const key = this._key;
    this._key = null; // single use
    const transcript = await sha256(concat(utf8(C.PROTOCOL_LABEL), utf8(reply.deviceId),
      this.pub, reply.pub, this.nonce, reply.nonce));
    let shared;
    try {
      const peer = await subtle().importKey("raw", reply.pub, { name: "X25519" }, false, []);
      shared = await subtle().deriveBits({ name: "X25519", public: peer }, key, 256);
    } catch {
      // e.g. a low-order public key, which WebCrypto refuses, like Python does
      throw new WrongCodeError("the device's public key is not usable");
    }
    const ikm = await subtle().importKey("raw", shared, "HKDF", false, ["deriveBits"]);
    const okm = new Uint8Array(await subtle().deriveBits(
      { name: "HKDF", hash: "SHA-256", salt: utf8(this._code), info: transcript }, ikm, 96 * 8));
    const confirmKey = await subtle().importKey("raw", okm.slice(64, 96),
      { name: "HMAC", hash: "SHA-256" }, false, ["sign", "verify"]);
    // subtle.verify compares in constant time (SPEC §5.1, review Q107).
    const ok = await subtle().verify("HMAC", confirmKey, reply.confirm,
      concat(utf8("device"), transcript));
    if (!ok) throw new WrongCodeError("setup code is wrong or this is not the right device");
    const tag = new Uint8Array(await subtle().sign("HMAC", confirmKey,
      concat(utf8("configurator"), transcript)));
    return {
      confirm: { type: "confirm", confirm: b64(tag) },
      keys: { c2d: okm.slice(0, 32), d2c: okm.slice(32, 64) },
    };
  }
}

// ---------------------------------------------------------------------------
// Envelopes (SPEC §5.3), configurator side: seal with c2d, open with d2c.

function gcmNonce(seq) {
  const nonce = new Uint8Array(12); // 4 zero bytes || seq as 8-byte big-endian
  new DataView(nonce.buffer).setBigUint64(4, BigInt(seq));
  return nonce;
}

const aad = (direction, seq) => utf8(`${C.PROTOCOL_LABEL}|${direction}|${seq}`);

export class Cipher {
  static async create(keys) {
    const load = (raw, use) => subtle().importKey("raw", raw, "AES-GCM", false, [use]);
    return new Cipher(await load(keys.c2d, "encrypt"), await load(keys.d2c, "decrypt"));
  }

  constructor(sendKey, receiveKey) {
    this._send = sendKey;
    this._receive = receiveKey;
    this._sendSeq = 0;
    this._receiveSeq = 0;
  }

  async seal(plaintext) {
    const seq = this._sendSeq;
    if (seq > C.MAX_SEQ) throw new ProtocolError("sequence numbers exhausted");
    const ct = new Uint8Array(await subtle().encrypt(
      { name: "AES-GCM", iv: gcmNonce(seq), additionalData: aad("c2d", seq) }, this._send,
      plaintext));
    this._sendSeq += 1;
    return { seq, ct: b64(ct) };
  }

  /** Only the next expected seq is accepted: replay, reordering and gaps all fail. */
  async open(envelope) {
    const seq = envelope.seq;
    if (seq !== this._receiveSeq) throw new ProtocolError("unexpected sequence number");
    let plaintext;
    try {
      plaintext = await subtle().decrypt(
        { name: "AES-GCM", iv: gcmNonce(seq), additionalData: aad("d2c", seq) }, this._receive,
        envelope.ct);
    } catch {
      throw new ProtocolError("authentication failed");
    }
    this._receiveSeq += 1;
    return new Uint8Array(plaintext);
  }
}

