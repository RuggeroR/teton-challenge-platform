# Protocol vectors, from the real Python code with fixed randomness


DEVICE_ID = "TETON-3F9A2C"
TYPED_CODE = "7k2m-qx9d-4htr-b8wz"  # as a technician might type it
WRONG_CODE = "ZYXWVTSRQPNMKJHG"
CONFIGURATOR_RANDOM = [bytes(range(1, 33)), bytes(range(100, 116))]  # private key, nonce
DEVICE_RANDOM = [bytes(range(200, 232)), bytes(range(50, 66))]


def fixed(chunks: list[bytes]) -> Callable[[int], bytes]:
    """A randbytes that hands out these values in order, checking the sizes."""
    queue: Iterator[bytes] = iter(chunks)

    def randbytes(n: int) -> bytes:
        value = next(queue)
        assert len(value) == n
        return value

    return randbytes


def _text(data: bytes) -> str:
    return data.decode("utf-8")


def vectors() -> dict[str, Any]:
    code = setup_code.normalize(TYPED_CODE)
    configurator = ConfiguratorHandshake(TYPED_CODE, fixed(CONFIGURATOR_RANDOM))
    device = DeviceHandshake(DEVICE_ID, code, fixed(DEVICE_RANDOM))
    hello = configurator.hello()
    reply = device.on_hello(hello)
    confirm, keys = configurator.on_hello_reply(reply)
    assert device.on_confirm(confirm) == keys

    wrong = ConfiguratorHandshake(WRONG_CODE, fixed(CONFIGURATOR_RANDOM))
    try:
        wrong.on_hello_reply(reply)
        raise AssertionError("a wrong code must be rejected")
    except HandshakeError:
        pass

    to_device = SessionCipher(keys, Role.CONFIGURATOR)
    to_configurator = SessionCipher(keys, Role.DEVICE)
    commands = [
        Scan(),
        SetCredentials(ssid="Café-Home", security=Security.WPA2_PSK, psk="correct-horse-battery"),
    ]
    statuses = [
        Ready(),
        ScanResult(
            networks=(
                NetworkInfo("Café-Home", 82, Security.WPA2_PSK),
                NetworkInfo("Hospital", 64, Security.WPA2_EAP_PEAP),
            )
        ),
        Status(state=StatusState.CONNECTING),
        Status(state=StatusState.FAILED, reason=FailureReason.WRONG_PASSWORD),
        Status(
            state=StatusState.CONNECTED,
            ip="192.168.43.17",
            internet=InternetStatus.FULL,
            warnings=(StatusWarning.LIMITED_INTERNET,),
        ),
        Error(code=ErrorCode.UNSUPPORTED_SECURITY),
    ]
    c2d = [
        {"plaintext": _text(encode(m)), "envelope": _text(encode(to_device.seal(encode(m))))}
        for m in commands
    ]
    d2c = [
        {"plaintext": _text(encode(m)), "envelope": _text(encode(to_configurator.seal(encode(m))))}
        for m in statuses
    ]
    payload = encode(to_device.seal(encode(Scan())))  # any payload longer than one chunk
    return {
        "setup_codes": {
            "valid": [{"typed": t, "code": setup_code.normalize(t)} for t in TYPING_VARIANTS]
            + [{"typed": "OOOO-IIII-LLLL-oil0", "code": "0000111111110110"}],
            "invalid": INVALID_CODES,
        },
        "framing": {
            "payload_hex": payload.hex(),
            "chunks_hex": [c.hex() for c in frame(payload)],
            "empty_chunks_hex": [c.hex() for c in frame(b"")],
        },
        "handshake": {
            "device_id": DEVICE_ID,
            "typed_code": TYPED_CODE,
            "wrong_code": WRONG_CODE,
            "configurator_private_hex": CONFIGURATOR_RANDOM[0].hex(),
            "configurator_nonce_hex": CONFIGURATOR_RANDOM[1].hex(),
            "hello": _text(encode(hello)),
            "hello_reply": _text(encode(reply)),
            "confirm": _text(encode(confirm)),
            "c2d_key_hex": keys.c2d.hex(),
            "d2c_key_hex": keys.d2c.hex(),
        },
        "c2d": c2d,
        "d2c": d2c,
        "info": _text(encode(Info(device_id=DEVICE_ID, state=DeviceState.ADVERTISING))),
    }


def vectors_json() -> str:
    return json.dumps(vectors(), indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    PROTOCOL_JS.write_text(with_block(PROTOCOL_JS.read_text(), protocol_js_block()))
    INDEX_HTML.write_text(with_block(INDEX_HTML.read_text(), index_html_block()))
    VECTORS.write_text(vectors_json())
    print(
        f"updated {PROTOCOL_JS.relative_to(ROOT)}, {INDEX_HTML.relative_to(ROOT)}, "
        f"{VECTORS.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
