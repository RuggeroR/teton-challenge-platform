def texts() -> dict[str, Any]:
    t: dict[str, Any] = {name: getattr(ui_text, name) for name in PAGE_TEXTS}
    # Templates: the functions of ui_text.py with {placeholders} where their arguments go.
    t["CONNECTING"] = ui_text.connecting_text("{ssid}")
    t["CONNECTED"] = {str(i): ui_text.connected_text("{ip}", i) for i in InternetStatus}
    t["FAILURES"] = {str(r): ui_text.failure_text(r) for r in FailureReason}
    t["ERRORS"] = {str(c): ui_text._ERRORS[c] for c in ErrorCode}  # {seconds}: "30 seconds"
    t["WARNINGS"] = {str(w): ui_text.warning_text(w) for w in StatusWarning}
    t["SECURITY_LABELS"] = {str(s): label for s, label in ui_text._SECURITY_LABELS.items()}
    t["BARS"] = ui_text._BARS
    return t


def js_block(name: str, value: Any, export: bool) -> str:
    body = json.dumps(value, indent=2, ensure_ascii=False)
    return f"{BEGIN}\n{'export ' if export else ''}const {name} = {body};\n{END}"


def with_block(text: str, block: str) -> str:
    """`text` with its marked block replaced. Fails if the markers are missing."""
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise ValueError("the generated block markers are missing")
    return pattern.sub(lambda _: block, text, count=1)


def protocol_js_block() -> str:
    return js_block("C", constants(), export=True)


def index_html_block() -> str:
    return js_block("T", texts(), export=False)


